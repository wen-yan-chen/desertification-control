"""Read-only M3 result extraction for the writing brief; never rerun a model."""
import hashlib
import json
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / 'Results/v7/model3'


def run():
    meta = json.loads((OUT / 'model3_results.json').read_text(encoding='utf-8'))
    for name, expected in meta['input_text_sha256_lf'].items():
        actual = hashlib.sha256((ROOT / name).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
        if actual != expected:
            raise ValueError(f'Stale M3 results: {name}')
    cohorts = pd.read_csv(OUT / 'initial_cohorts.csv')
    annual = pd.read_csv(OUT / 'project_annual.csv')
    summary = pd.read_csv(OUT / 'summary.csv')
    chains = json.loads((OUT / 'markov_diagnostics.json').read_text())
    checks = json.loads((OUT / 'validation_summary.json').read_text())
    if hashlib.sha256((ROOT/'Code/v7_m3_grid_check.py').read_bytes().replace(b'\r\n',b'\n')).hexdigest() != checks['checker_sha256_lf']:
        raise ValueError('Stale M3 grid validation')
    ids = list(cohorts.cohort_id)
    labels = dict(zip(ids, ['A', 'B', 'C']))
    parts = ['% Generated by Reports/M3/build_tables.py. Do not edit numeric tables.']

    def table(command, spec, header, rows):
        parts.append('\\newcommand{\\' + command + '}{%\n\\begin{tabular}{@{}' + spec + '@{}}\n\\toprule\n' +
                     header + r' \\' + '\n\\midrule\n' + '\n'.join(' & '.join(row) + r' \\' for row in rows) +
                     '\n\\bottomrule\n\\end{tabular}}')

    table('InitialTable', 'lrrrrr', r'Cohort & Area (ha) & Planting year & $V_0$ (\%) & $M_0$ (mm) & Quota (mm/yr)',
          [[labels[r.cohort_id],f'{r.area_ha:.0f}',r.cohort_id.split('_')[1][1:],f'{r.V_end_pct:.3f}',f'{r.M_end_mm:.3f}',f'{r.irrigation_mm_yr:.0f}'] for r in cohorts.itertuples()])
    base = annual[(annual['case']=='base_nonstationary') & annual.post_year.isin([10,30,50])]
    table('BaseTable','rrrrrr',r'Year & First hit (\%) & 95\% Wilson interval & Low area (ha) & Ever-hit area (ha) & $H_{\rm eco}$',
          [[str(r.post_year),f'{100*r.project_failure_probability:.2f}',f'[{100*r.ci95_low:.3f}, {100*r.ci95_high:.3f}]',f'{r.expected_current_failed_area_ha:.2f}',f'{r.expected_ever_failed_area_ha:.2f}',f'{r.cumulative_cover_ha_year_mean:.2f}'] for r in base.itertuples()])
    bs = summary[summary['case']=='base_nonstationary']
    table('CohortTable','lrrrrr',r'Entity & $p_{50}$ (\%) & RMST (yr) & MC SE (yr) & Censored & Final $V$ (\%)',
          [[labels.get(r.entity,'Project'),f'{100*r.p_failure:.2f}',f'{r.restricted_mean_first_passage_years:.3f}',f'{r.restricted_mean_mc_se:.3f}',str(r.censored_count),f'{r.V_final_mean_pct:.3f}'] for r in bs.itertuples()])
    cases = [('base_nonstationary','Base'),('stationary_reference','Stationary'),('no_storm','No storms'),('no_drought','No drought'),('no_random_disasters','No random disasters'),('stable_no_disasters','Stable, no disasters'),('no_irrigation','No irrigation'),('water_80pct','Water request 80\\%'),('water_120pct','Water request 120\\%'),('storm_at_year_start','Start-year shocks'),('independent_cohort_storms','Independent storms'),('no_drought_storm_association','No drought--storm link'),('fixed_mean_loss','Fixed loss per event'),('threshold_20pctK','Threshold $0.20K$'),('threshold_40pctK','Threshold $0.40K$'),('wind_trend_only','Wind trend only'),('rain_trend_only','Rain trend only'),('wetter_calmer','Wetter, calmer')]
    rows=[]
    for name,label in cases:
        s=summary[(summary['case']==name)&(summary.entity=='project')].iloc[0]
        p=annual[(annual['case']==name)&(annual.post_year==50)].iloc[0]
        p10=annual[(annual['case']==name)&(annual.post_year==10)].iloc[0]
        rows.append([label,f'{100*p10.project_failure_probability:.2f}',f'{100*s.p_failure:.2f}',f'{s.restricted_mean_first_passage_years:.2f}',f'{p.cumulative_cover_ha_year_mean:.1f}'])
    table('SensitivityTable','lrrrr',r'Scenario & $p_{10}$ (\%) & $p_{50}$ (\%) & RMST (yr) & $H_{\rm eco}(50)$',rows)
    rows=[]
    for rate in (.1,.25,.5):
        for loss in (.15,.3,.45):
            s=summary[(summary['case']==f'joint_rate_{rate}_loss_{loss}')&(summary.entity=='project')].iloc[0]
            rows.append([f'{rate:.2f}',f'{loss:.2f}',f'{100*s.p_failure:.2f}',f'{s.restricted_mean_first_passage_years:.2f}'])
    table('JointTable','rrrr',r'$\lambda_0$ & $\mathrm{E}[U]$ & $p_{50}$ (\%) & RMST (yr)',rows)
    table('ChainTable','lrrr',r'Cohort & Stationary mean (yr) & Variance (yr$^2$) & RMST(50) (yr)',
          [[labels[d['cohort_id']],f"{d['expected_first_passage_years']:.3f}",f"{d['variance_first_passage_years2']:.3f}",f"{d['restricted_mean_first_passage_years']:.3f}"] for d in chains if d['nv']==321])
    def macro(key,value): parts.append('\\newcommand{\\'+key+'}{'+value+'}')
    macro('StateError',f"{100*max(d['max_absolute_probability_difference'] for d in checks['state_and_quadrature_checks'] if d['comparison']=='state_grid'):.4f}")
    macro('ShockError',f"{100*max(d['max_absolute_probability_difference'] for d in checks['state_and_quadrature_checks'] if d['comparison']=='shock_quadrature'):.4f}")
    macro('MCError',f"{100*checks['max_markov_mc_absolute_difference']:.3f}")
    macro('Threshold',f"{meta['config']['failure_cover_fraction_K']*meta['m1_parameters']['K_section_pct']:.3f}")
    (HERE/'m3_result_tables.tex').write_text('\n\n'.join(parts)+'\n',encoding='utf-8')
    print('Verified M3 provenance and generated 6 report tables; no model outputs changed.')


if __name__=='__main__':
    run()
