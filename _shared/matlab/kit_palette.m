function P = kit_palette(name)
%KIT_PALETTE Named six-colour palettes for paper_style('palette', name).
%   kit_palette() lists the names. Every palette is ordered by role, so any
%   chart or paper figure can be re-coloured without touching its code:
%     1 main (water, first series)   2 accent (highlight, second series)
%     3 green (vegetation, benefit)  4 purple (scenario contrasts)
%     5 earth (sand, cost)           6 extra (second blue or teal)
%   Limits and thresholds stay red dashed in every palette.
%   P has fields name, title, source, safe (colour-blind safe as published)
%   and cycle (6-by-3 RGB).
T = { ...
 'oasis',     'Oasis (paper default)', 'final paper, mycolor.space',      false, {'1E5F74','F49431','2B633C','7A437F','8F7159','00828C'}; ...
 'economist', 'The Economist',         'Economist Style Guide 2017',      false, {'006BA2','DB444B','379A8B','9A607F','D1B07C','3EBCD2'}; ...
 'nejm',      'NEJM',                  'ggsci, New England J. Med.',      false, {'0072B5','E18727','20854E','7876B1','BC3C29','6F99AD'}; ...
 'hiroshige', 'Hiroshige',             'MetBrewer (Ukiyo-e)',             true,  {'376795','EF8A47','72BCD5','E76254','F7AA58','1E466E'}; ...
 'nord',      'Nord',                  'Arctic Ice Studio, Frost+Aurora', false, {'5E81AC','D08770','A3BE8C','B48EAD','BF616A','88C0D0'}; ...
 'sailboat',  'Sailboat',              'PNWColors (soft coastal)',        false, {'6E7CB9','E89C81','D0E2AF','D2848D','F5DB99','7BBCD5'}; ...
 'tol_muted', 'Tol muted',             'Paul Tol, SRON technical note',   true,  {'332288','CC6677','117733','882255','DDCC77','44AA99'}; ...
 'vangogh',   'VanGogh 1',             'MetBrewer (cool botanical)',      false, {'2C2D54','6F9954','87BCBD','6B6CA3','89AB7C','434475'}};
if nargin < 1, P = T(:, 1)'; return; end
i = find(strcmp(T(:, 1), name), 1);
if isempty(i), error('kit_palette:name', 'Unknown palette "%s". Try: %s.', name, strjoin(T(:, 1)', ', ')); end
P = struct('name', T{i, 1}, 'title', T{i, 2}, 'source', T{i, 3}, 'safe', T{i, 4});
P.hex = T{i, 5};
P.cycle = cell2mat(cellfun(@hex2rgb, P.hex(:), 'UniformOutput', false));
end
