function style_axes(ax, S, grid)
%STYLE_AXES Axes in the 阿昆的科研日常 template style.
%   grid = 'y' (default), 'x', 'xy' or 'none' for light reference lines.
if nargin < 3, grid = 'y'; end
set(ax, 'Box', 'off', ...
    'TickDir', 'out', 'TickLength', [0.02 0.02], ...
    'XMinorTick', 'off', 'YMinorTick', 'off', ...
    'LineWidth', 0.6, 'XColor', S.c.axis, 'YColor', S.c.axis, ...
    'FontName', S.font, 'FontSize', S.fs.tick, ...
    'XGrid', 'off', 'YGrid', 'off', ...
    'GridColor', S.c.grid, 'GridAlpha', 1, 'GridLineStyle', '-', 'GridLineWidth', 0.5, ...
    'Color', 'none', 'TickLabelInterpreter', 'tex');
ax.XLabel.FontSize = S.fs.label;
ax.YLabel.FontSize = S.fs.label;
ax.XLabel.Color = S.c.ink;
ax.YLabel.Color = S.c.ink;
if contains(grid, 'x'), ax.XGrid = 'on'; end
if contains(grid, 'y'), ax.YGrid = 'on'; end
hold(ax, 'on');
end
