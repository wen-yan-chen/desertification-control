function fig = new_figure(w_cm, h_cm)
%NEW_FIGURE Invisible white figure at its printed size (cm).
fig = figure('Visible', 'off', 'Units', 'centimeters', ...
    'Position', [2 2 w_cm h_cm], 'Color', 'w', ...
    'PaperUnits', 'centimeters', 'PaperPosition', [0 0 w_cm h_cm], ...
    'PaperSize', [w_cm h_cm], 'Renderer', 'painters');
end
